// node scripts/bake-superknight-mesh.mjs <knight.bin> <knight.json>
// Wraps the baked knight buffer (made by static/models/superknight-bake.py on the
// Hunyuan3D-2 output) into src/modes/superknight-mesh.js: a lazily imported chunk, so
// only the superknight mode ever downloads it.
import { readFileSync, writeFileSync } from 'node:fs';
const [bin, json] = process.argv.slice(2);
const buf = readFileSync(bin), meta = JSON.parse(readFileSync(json, 'utf8'));
const need = meta.nv * 11 + meta.nt * 6;
if (buf.length !== need) { console.error(`size mismatch: ${buf.length} bytes, expected ${need}`); process.exit(1); }
const out = '// generated by scripts/bake-superknight-mesh.mjs: do not edit\n' +
  '// knight mesh: Hunyuan3D-2 (shape + texture) from a GPT-Image concept, decimated + quantised\n' +
  `export var META = ${JSON.stringify(meta)};\n` +
  `export var DATA = '${buf.toString('base64')}';\n`;
writeFileSync(new URL('../src/modes/superknight-mesh.js', import.meta.url), out);
console.log(`wrote src/modes/superknight-mesh.js: ${meta.nv} verts, ${meta.nt} tris, ${out.length} bytes`);
